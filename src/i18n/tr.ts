// Structural shape: same keys, string leaves. Use this for translation mirrors
// so en.ts doesn't need to repeat each literal value as the exact TR string.
export type DictionaryShape<T> = {
  [K in keyof T]: T[K] extends string ? string : T[K] extends object ? DictionaryShape<T[K]> : T[K]
}

export type TrDictionary = DictionaryShape<typeof tr>
